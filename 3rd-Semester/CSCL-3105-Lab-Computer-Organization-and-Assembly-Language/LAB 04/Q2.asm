.MODEL SMALL
.STACK 100H

.DATA
BALANCE DB 8
WITHDRAW DB 5
MSG1 DB 'SUFFICIENT BALANCE$'
MSG2 DB 'INSUFFICIENT BALANCE$'

.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX
    MOV AL,BALANCE
    CMP AL, WITHDRAW
    JAE SUFF
    
    LEA DX,MSG2
    MOV AH,09H
    INT 21H
    JMP EXIT
    
    SUFF:
    LEA DX, MSG1
    MOV AH, 09H
    INT 21H
    
    EXIT:
    MOV AH, 4CH
    INT 21H
    
MAIN ENDP
END MAIN