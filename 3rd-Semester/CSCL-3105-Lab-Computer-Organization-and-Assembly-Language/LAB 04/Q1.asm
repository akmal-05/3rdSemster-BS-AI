.MODEL SMALL
.STACK 100H
.DATA
AGE DB 20
MSG1 DB 'Eligible for driving license$'
MSG2 DB 'Not eligible for driving license$'
.CODE
MAIN PROC
MOV AX, @DATA
MOV DS, AX
MOV AL, AGE
CMP AL, 18
JAE ELIGIBLE
LEA DX, MSG2
MOV AH, 09H
INT 21H
JMP EXIT
ELIGIBLE:
LEA DX, MSG1
MOV AH, 09H
INT 21H
EXIT:
MOV AH, 4CH
INT 21H
MAIN ENDP
END MAIN